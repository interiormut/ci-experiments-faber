//! The Traefik dynamic-configuration document, and how it is serialized.
//!
//! **The file is written as JSON with a `.yml` extension, and that is
//! deliberate.** Traefik's file provider picks a decoder from the extension
//! and skips what it does not recognise — a `.json` file is dropped with only
//! a debug-level `Skipping file, unsupported extension`, which is exactly the
//! kind of silence that costs an afternoon. YAML is recognised, and JSON is a
//! subset of YAML, so a `.yml` file containing JSON is parsed by Traefik's
//! YAML decoder and produces the routers. Both halves of that were checked
//! against `traefik:v3` rather than assumed.
//!
//! The payoff is that the workspace's existing `serde_json` does the writing
//! and no YAML crate joins the dependency graph for a document that is four
//! nested maps of strings. If that trade ever stops being worth it,
//! [`render`] is the single function to change: swap the serializer, change
//! the extension the operator is told to use, and nothing above this module
//! moves.
//!
//! The document is rewritten in full on every change. It is a projection of
//! the manager's entry set, not an accumulation, so a partially applied
//! previous write cannot survive into the next one.

use std::collections::BTreeMap;

use serde::Serialize;

use crate::config::Config;
use crate::entry::Entry;
use crate::error::Result;

/// Leading YAML comment. Legal because the file is read as YAML even though
/// its body is JSON, and worth the oddity: the first thing an operator who
/// opens this file needs to know is that their edits will be overwritten.
const BANNER: &str =
    "# Generated by Faber. Rewritten in full on every change — do not edit by hand.\n";

#[derive(Serialize)]
pub(crate) struct Document {
    http: Http,
}

#[derive(Serialize)]
struct Http {
    routers: BTreeMap<String, Router>,
    services: BTreeMap<String, Service>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct Router {
    rule: String,
    service: String,
    entry_points: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    tls: Option<Tls>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct Tls {
    #[serde(skip_serializing_if = "Option::is_none")]
    cert_resolver: Option<String>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct Service {
    load_balancer: LoadBalancer,
}

#[derive(Serialize)]
struct LoadBalancer {
    servers: Vec<Server>,
}

#[derive(Serialize)]
struct Server {
    url: String,
}

/// The router and service name for an entry.
///
/// The domain goes in verbatim rather than slugified. Traefik map keys
/// tolerate dots, and a `.` → `-` slug is not injective: `example.com` and
/// `example-com` would collapse onto one key, and one entry would quietly
/// eat the other. Verbatim is injective by construction, so distinct domains
/// are distinct routers with no uniqueness bookkeeping anywhere.
pub(crate) fn name_for(config: &Config, entry: &Entry) -> String {
    format!("{}{}", config.name_prefix, entry.domain)
}

/// Render the whole entry set as one dynamic-configuration document.
pub(crate) fn render<'a>(
    config: &Config,
    entries: impl IntoIterator<Item = &'a Entry>,
) -> Result<String> {
    let mut routers = BTreeMap::new();
    let mut services = BTreeMap::new();

    for entry in entries {
        let name = name_for(config, entry);
        routers.insert(
            name.clone(),
            Router {
                // Safe only because `Domain` rejects every character that
                // could close the literal or extend the expression.
                rule: format!("Host(`{}`)", entry.domain),
                service: name.clone(),
                entry_points: config.entry_points.clone(),
                tls: config.tls.then(|| Tls {
                    cert_resolver: config.cert_resolver.clone(),
                }),
            },
        );
        services.insert(
            name,
            Service {
                load_balancer: LoadBalancer {
                    servers: vec![Server {
                        url: entry.target.upstream(&config.placement),
                    }],
                },
            },
        );
    }

    let document = Document {
        http: Http { routers, services },
    };
    let mut out = String::from(BANNER);
    out.push_str(&serde_json::to_string_pretty(&document)?);
    out.push('\n');
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::Placement;
    use crate::domain::Domain;
    use crate::entry::Target;

    fn config() -> Config {
        Config::new("/tmp/faber.yml", Placement::Host)
    }

    fn entry(domain: &str, target: Target) -> Entry {
        Entry::new(Domain::new(domain).unwrap(), target)
    }

    fn body(rendered: &str) -> serde_json::Value {
        serde_json::from_str(rendered.strip_prefix(BANNER).expect("banner")).unwrap()
    }

    #[test]
    fn renders_a_router_and_a_service_per_entry() {
        let entries = vec![entry(
            "example.com",
            Target::container("web", 8080).unwrap(),
        )];
        let doc = body(&render(&config(), &entries).unwrap());

        let router = &doc["http"]["routers"]["faber-example.com"];
        assert_eq!(router["rule"], "Host(`example.com`)");
        assert_eq!(router["service"], "faber-example.com");
        assert_eq!(router["entryPoints"][0], "websecure");
        assert!(router["tls"].is_object());
        assert_eq!(
            doc["http"]["services"]["faber-example.com"]["loadBalancer"]["servers"][0]["url"],
            "http://web:8080"
        );
    }

    #[test]
    fn names_stay_distinct_for_domains_a_slug_would_collapse() {
        let entries = vec![
            entry("example.com", Target::host(3000).unwrap()),
            entry("example-com", Target::host(3001).unwrap()),
        ];
        let doc = body(&render(&config(), &entries).unwrap());
        let routers = doc["http"]["routers"].as_object().unwrap();
        assert_eq!(routers.len(), 2, "one entry ate the other");
    }

    #[test]
    fn tls_and_resolver_follow_the_config() {
        let entries = vec![entry("example.com", Target::host(3000).unwrap())];

        let plain = body(&render(&config().without_tls(), &entries).unwrap());
        assert!(plain["http"]["routers"]["faber-example.com"]["tls"].is_null());

        let acme = body(&render(&config().with_cert_resolver("letsencrypt"), &entries).unwrap());
        assert_eq!(
            acme["http"]["routers"]["faber-example.com"]["tls"]["certResolver"],
            "letsencrypt"
        );
    }

    #[test]
    fn an_empty_entry_set_renders_an_empty_document() {
        let doc = body(&render(&config(), &[]).unwrap());
        assert!(doc["http"]["routers"].as_object().unwrap().is_empty());
        assert!(doc["http"]["services"].as_object().unwrap().is_empty());
    }
}
